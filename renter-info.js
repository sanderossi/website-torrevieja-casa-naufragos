  function cardHtml(card) {
    const link = card.link && card.url
      ? `<a class="renter-card-link" href="${card.url}" target="_blank" rel="noopener noreferrer">${card.link} →</a>`
      : '';
    return `<article class="renter-card"><span class="renter-icon">${checkIcon}</span><h3>${card.title}</h3><p>${card.text}</p>${link}</article>`;
  }

  function sectionHeader(data) {
    return `<p class="renter-kicker">${data.kicker}</p><h2 class="renter-heading">${data.heading}</h2><p class="renter-sub">${data.sub}</p>`;
  }

