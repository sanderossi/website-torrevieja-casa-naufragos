  let scheduled = false;
  function apply() {
    scheduled = false;
    addStyles();
    const data = copy[currentLang()] || copy.en;
    const location = document.getElementById('location');
    const apartment = document.getElementById('apartment');
    const pricing = document.getElementById('pricing');
    if (!location || !apartment || !pricing) return;

    ensureSection('arrival-ease', 'renter-section', renderArrival(data.arrival), location, 'after');
    ensureSection('practical-stay', 'renter-section', renderPractical(data.practical), apartment, 'after');
    ensureSection('good-to-know-summary', 'renter-section bg-sand', renderSummary(data.summary), pricing, 'before');
    ensureFaq(data.faq);
  }

  function schedule() {
    if (scheduled) return;
    scheduled = true;
    requestAnimationFrame(apply);
  }

  schedule();
  new MutationObserver(schedule).observe(document.documentElement, {
    childList: true,
    subtree: true,
    attributes: true,
    attributeFilter: ['lang']
  });
